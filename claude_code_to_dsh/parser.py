"""Claude-code-to-dsh: extract continuable context from Claude Code session JSONL.

The philosophy: do NOT replay tool-call events. Extract what actually carries
value across sessions — the auto-compact ``summary`` chain, the first real
user prompt, the files that were touched, and the tail state of the
conversation — and render them as a markdown continuation doc or a plain-text
seed block for a new DeepSeek Harness session.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Optional

__version__ = "0.1.0"

# Markers of system-injected first messages that are NOT the user's real prompt.
_SKIP_MARKERS = (
    "caveat",
    "ide_opened_file",
    "command-message",
    "command-name",
    "the user opened",
    "generated by the user while running local commands",
    "may or may not be related",
    "<mcp-",
    "session started",
)

# tool_use entries that reveal file footprints: name -> op label
_FILE_TOOL_OPS = {
    "Write": "Write",
    "MultiEdit": "Edit",
    "Edit": "Edit",
    "Read": "Read",
    "NotebookEdit": "Edit",
}

_TAG_RE = re.compile(r"^\s*<[^>]+>\s*")


@dataclass
class Summary:
    """One auto-compact summary line (chronological order)."""

    text: str
    timestamp: Optional[float] = None


@dataclass
class SessionInfo:
    """Everything worth knowing about one Claude Code session."""

    session_id: str
    raw_path: str
    project_key: str
    size_bytes: int
    mtime: float
    cwd: Optional[str] = None  # exact project path from message `cwd` field

    first_user_prompt: Optional[str] = None
    ai_titles: list[str] = field(default_factory=list)      # `ai-title` lines (newest last)
    summaries: list[Summary] = field(default_factory=list)  # auto-compact summaries (chronological)
    last_prompts: list[str] = field(default_factory=list)   # `last-prompt` snapshots (newest last)
    footprints: dict[str, list[str]] = field(default_factory=dict)

    user_messages: int = 0
    assistant_messages: int = 0
    tool_calls: int = 0
    error_results: int = 0
    last_user_messages: list[str] = field(default_factory=list)
    last_assistant_text: Optional[str] = None
    first_ts: Optional[float] = None
    last_ts: Optional[float] = None
    local_command_mode: bool = False  # messages are mostly command injections, not human Q&A

    # -- derived helpers -------------------------------------------------
    @property
    def project_dir(self) -> str:
        """Exact cwd when available; else best-effort decode of the folder key."""
        if self.cwd:
            return self.cwd
        return decode_project_key(self.project_key)

    @property
    def title(self) -> str:
        """Newest AI title > newest compact summary > first real prompt."""
        if self.ai_titles:
            return _clean(self.ai_titles[-1])
        if self.summaries:
            return _clean(self.summaries[-1].text)
        if self.first_user_prompt:
            return _clean(self.first_user_prompt)
        return "(无文本)"

    @property
    def summary_chain(self) -> list[str]:
        return [_clean(s.text) for s in self.summaries]

    @property
    def edited_files(self) -> list[tuple[str, str]]:
        """(path, ops) pairs for files that were written/edited (not just read)."""
        out = []
        for path, ops in sorted(self.footprints.items()):
            if any(op in ("Write", "Edit") for op in ops):
                out.append((path, ", ".join(ops)))
        return out

    @property
    def read_files(self) -> list[str]:
        return sorted(
            p for p, ops in self.footprints.items() if ops == ["Read"]
        )

    @property
    def time_range(self) -> str:
        def fmt(ts: Optional[float]) -> str:
            if ts is None:
                return "?"
            return datetime.fromtimestamp(ts, timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        return f"{fmt(self.first_ts)} → {fmt(self.last_ts)}"


# --------------------------------------------------------------------------
# path / text helpers
# --------------------------------------------------------------------------

def decode_project_key(key: str) -> str:
    """Best-effort decode of a Claude Code project dir name to a path.

    Claude Code encodes a path by replacing ``/`` with ``-`` WITHOUT escaping
    dashes inside segments (``-Users-ch-code-xushang-code`` ←
    ``/Users/ch/code/xushang-code``), so plain splitting is ambiguous. We
    enumerate every way of merging adjacent split segments and return the
    deepest candidate that exists on the local filesystem; fall back to a
    plain join when nothing matches. Display purposes only.
    """
    segs = [s for s in key.lstrip("-").split("-") if s]
    if not segs:
        return key
    n = len(segs)
    best = None  # (depth, path, merges)
    for mask in range(1 << (n - 1)):
        parts: list[str] = []
        cur = segs[0]
        for g in range(n - 1):
            if mask & (1 << g):
                cur = cur + "-" + segs[g + 1]
            else:
                parts.append(cur)
                cur = segs[g + 1]
        parts.append(cur)
        cand = "/" + "/".join(parts)
        if os.path.isdir(cand):
            merges = bin(mask).count("1")
            if best is None or len(parts) > best[0] or (len(parts) == best[0] and merges < best[2]):
                best = (len(parts), cand, merges)
    if best:
        return best[1]
    return "/" + "/".join(segs)


def _clean(text: str, limit: int = 400) -> str:
    """Collapse whitespace, strip leading tag blocks, truncate."""
    text = " ".join(text.split())
    while text.startswith("<") and ">" in text:
        text = text[text.index(">") + 1 :].strip()
    return text[:limit]


def _extract_text(content) -> str:
    """Pull human text out of a Claude Code message content blob.

    Only ``text`` blocks count as human prose; embedded ``tool_use`` /
    ``tool_result`` blocks are handled separately by the caller.
    """
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for c in content:
            if isinstance(c, dict) and c.get("type") == "text" and isinstance(c.get("text"), str):
                parts.append(c["text"])
        return " ".join(parts)
    return ""


def _record_footprint(info: SessionInfo, tool: dict) -> None:
    """Record a file footprint from one tool_use dict (top-level or embedded)."""
    name_tool = tool.get("name") or ""
    op = _FILE_TOOL_OPS.get(name_tool)
    if not op:
        return
    inp = tool.get("input") or {}
    path_field = inp.get("file_path") or inp.get("path")
    if isinstance(path_field, str) and path_field:
        ops = info.footprints.setdefault(path_field, [])
        if op not in ops:
            ops.append(op)


def _is_real_prompt(text: str) -> bool:
    low = text.lower()
    return bool(text) and not any(m in low for m in _SKIP_MARKERS) and not text.startswith("<")


