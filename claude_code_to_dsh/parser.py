def default_projects_root() -> str:
    return os.path.join(os.path.expanduser("~"), ".claude", "projects")


def list_session_files(projects_root: Optional[str] = None) -> list[tuple[str, str]]:
    """Return (jsonl_path, project_key) pairs, newest first."""
    root = projects_root or default_projects_root()
    found = []
    if not os.path.isdir(root):
        return found
    for entry in sorted(os.listdir(root)):
        pdir = os.path.join(root, entry)
        if not os.path.isdir(pdir):
            continue
        for name in sorted(os.listdir(pdir)):
            if name.endswith(".jsonl"):
                found.append((os.path.join(pdir, name), entry))
    found.sort(key=lambda t: os.path.getmtime(t[0]), reverse=True)
    return found


def parse_session(path: str, project_key: Optional[str] = None,
                  max_lines: Optional[int] = None,
                  tail_size: int = 3) -> SessionInfo:
    """Parse one Claude Code JSONL session file."""
    name = os.path.basename(path)
    session_id = name[:-6] if name.endswith(".jsonl") else name
    stat = os.stat(path)
    info = SessionInfo(
        session_id=session_id,
        raw_path=path,
        project_key=project_key or os.path.basename(os.path.dirname(path)),
        size_bytes=stat.st_size,
        mtime=stat.st_mtime,
    )

    first_user_texts: list[str] = []  # first N user texts, for command-mode detection
    with open(path, encoding="utf-8", errors="replace") as fh:
        for i, line in enumerate(fh):
            if max_lines is not None and i >= max_lines:
                break
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                continue
            if not isinstance(obj, dict):
                continue

            if info.cwd is None:
                cwd = obj.get("cwd")
                if isinstance(cwd, str) and cwd.strip():
                    info.cwd = os.path.normpath(cwd)

            t = obj.get("type")
            ts = obj.get("timestamp")
            if isinstance(ts, str):
                # Claude Code writes ISO-8601 (e.g. '2026-08-01T09:46:53.118Z')
                try:
                    s = ts[:-1] if ts.endswith("Z") else ts
                    ts = datetime.fromisoformat(s).timestamp()
                except ValueError:
                    ts = None
            else:
                try:
                    ts = float(ts) if ts is not None else None
                except (TypeError, ValueError):
                    ts = None
            if ts is not None:
                if info.first_ts is None or ts < info.first_ts:
                    info.first_ts = ts
                if info.last_ts is None or ts > info.last_ts:
                    info.last_ts = ts

            if t == "ai-title":
                title = obj.get("aiTitle")
                if isinstance(title, str) and title.strip():
                    info.ai_titles.append(title.strip())

            elif t == "summary":
                s = obj.get("summary")
                if isinstance(s, str) and s.strip():
                    info.summaries.append(Summary(text=s.strip(), timestamp=ts))

            elif t == "last-prompt":
                lp = obj.get("lastPrompt")
                if isinstance(lp, str) and lp.strip():
                    info.last_prompts.append(lp.strip())
                    if len(info.last_prompts) > tail_size:
                        info.last_prompts.pop(0)

            elif t == "user":
                info.user_messages += 1
                content = (obj.get("message") or {}).get("content")
                # embedded tool_result blocks (modern JSONL)
                if isinstance(content, list):
                    for c in content:
                        if isinstance(c, dict) and c.get("type") == "tool_result" and c.get("is_error"):
                            info.error_results += 1
                text = _extract_text(content)
                text = _clean(text, limit=2000)
                if text:
                    if len(first_user_texts) < 10:
                        first_user_texts.append(text)
                    if info.first_user_prompt is None and _is_real_prompt(text):
                        info.first_user_prompt = text
                    info.last_user_messages.append(text)
                    if len(info.last_user_messages) > tail_size:
                        info.last_user_messages.pop(0)

            elif t == "assistant":
                info.assistant_messages += 1
                content = (obj.get("message") or {}).get("content")
                text = _extract_text(content)
                if text.strip():
                    info.last_assistant_text = _clean(text, limit=1500)
                # embedded tool_use blocks (modern JSONL)
                if isinstance(content, list):
                    for c in content:
                        if isinstance(c, dict) and c.get("type") == "tool_use":
                            info.tool_calls += 1
                            _record_footprint(info, c)

            elif t == "tool_use":  # legacy top-level rows
                info.tool_calls += 1
                _record_footprint(info, obj)

            elif t == "tool_result":  # legacy top-level rows
                if obj.get("is_error"):
                    info.error_results += 1

    # Dedupe last-user list (same text repeated by tool wrapper)
    seen, deduped = set(), []
    for m in info.last_user_messages:
        if m not in seen:
            seen.add(m)
            deduped.append(m)
    info.last_user_messages = deduped[-tail_size:]

    # local-command mode detection: most of the first messages are injections
    if first_user_texts:
        injected = sum(1 for t in first_user_texts if not _is_real_prompt(t))
        info.local_command_mode = injected / len(first_user_texts) >= 0.6
    return info
