class ParserTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.path = os.path.join(self.tmp, "abc12345-0000-0000-0000-000000000000.jsonl")
        with open(self.path, "w", encoding="utf-8") as fh:
            for line in SAMPLE:
                fh.write(json.dumps(line, ensure_ascii=False) + "\n")

    def test_parse_basics(self):
        info = parse_session(self.path, project_key="-Users-ch-code-xushang-code")
        self.assertEqual(info.user_messages, 3)
        self.assertEqual(info.assistant_messages, 3)
        # 2 legacy top-level tool_use + 1 embedded in assistant content
        self.assertEqual(info.tool_calls, 3)
        # 1 legacy top-level tool_result + 1 embedded in user content
        self.assertEqual(info.error_results, 2)
        self.assertEqual(len(info.summaries), 2)
        self.assertEqual(info.first_user_prompt, "这个 services/forum 模块是干嘛的")
        # ai-title wins over summary
        self.assertEqual(info.title, "forum 模块调研与修复")
        self.assertEqual(info.last_prompts[-1], "修复后重新跑一遍测试")
        self.assertEqual(info.project_dir, "/Users/ch/code/xushang-code")
        self.assertFalse(info.local_command_mode)

    def test_footprints(self):
        info = parse_session(self.path)
        self.assertEqual(info.footprints["services/forum/src/main.py"], ["Read", "Edit"])
        self.assertEqual(info.footprints["services/forum/tests/test_main.py"], ["Write"])
        edited = info.edited_files
        self.assertEqual(len(edited), 2)
        self.assertEqual(edited[0][0], "services/forum/src/main.py")

    def test_tail(self):
        info = parse_session(self.path)
        self.assertIn("好,继续", info.last_user_messages)
        self.assertIn("完成,待验证部署。", info.last_assistant_text)

    def test_skip_injected_first_prompt(self):
        lines = [
            {
                "type": "user",
                "message": {
                    "role": "user",
                    "content": "<local-command-caveat>Caveat: generated by the user while running local commands. DO NOT respond.",
                },
                "timestamp": 1.0,
            },
            {
                "type": "user",
                "message": {"role": "user", "content": "真正的提问"},
                "timestamp": 2.0,
            },
        ]
        path = os.path.join(self.tmp, "skip.jsonl")
        with open(path, "w", encoding="utf-8") as fh:
            for line in lines:
                fh.write(json.dumps(line, ensure_ascii=False) + "\n")
        info = parse_session(path)
        self.assertEqual(info.first_user_prompt, "真正的提问")

    def test_local_command_mode(self):
        lines = [
            {
                "type": "user",
                "message": {
                    "role": "user",
                    "content": f"<local-command-caveat>Caveat: generated {i} while running local commands.",
                },
                "timestamp": float(i),
            }
            for i in range(8)
        ]
        path = os.path.join(self.tmp, "cmd.jsonl")
        with open(path, "w", encoding="utf-8") as fh:
            for line in lines:
                fh.write(json.dumps(line, ensure_ascii=False) + "\n")
        info = parse_session(path)
        self.assertTrue(info.local_command_mode)
        self.assertIsNone(info.first_user_prompt)

    def test_decode_project_key(self):
        self.assertEqual(decode_project_key("-Users-ch-code-xushang-code"), "/Users/ch/code/xushang-code")
        self.assertEqual(decode_project_key("-tmp"), "/tmp")

    def test_renderers(self):
        info = parse_session(self.path)
        md = render_markdown(info)
        self.assertIn("# 会话续接文档", md)
        self.assertIn("services/forum/src/main.py", md)
        self.assertIn("中期摘要", md)
        seed = render_seed(info)
        self.assertIn("续接上下文", seed)
        self.assertIn("这个 services/forum 模块是干嘛的", seed)


